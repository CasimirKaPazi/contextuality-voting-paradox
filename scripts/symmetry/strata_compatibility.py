"""Strata of voter groups that are not products (working note *Equivariant Obstructions*, Section 6).

Four alternatives, neutrality (all renamings), continuous rules on the realised sphere of rankings.
For a group P of voter permutations, K = P x S_4.

Part 1 samples permutation groups on up to seven voters (closures of one or two random permutations)
and keeps those without a fixed voter whose orbit sizes have gcd 1, so that the top stage vanishes.
For each it evaluates the obstructions of Proposition 6 on the strata of single elements (with
centralisers). Most are obstructed; the exceptions are groups such as S_3 acting on three voters and,
through the sign, on two more.

Part 2 sets up, for each exception, the compatible system on the strata whose target is the circle
fixed by a transposition tau: one integer degree per short orbit of each subgroup H of P x <tau> that
contains an element renaming by tau; on each stratum the degrees sum to 1 (unanimity); conjugate and
normalising elements preserve them (signs cancel); and where H is contained in H2, the degrees of the
smaller stratum X^{H2} are the sums of those of X^H over its short orbits (long orbits contribute 0).
Subgroups are generated by up to three elements. Every exception is obstructed by this system, and
every sampled group with a fixed voter (where the dictatorship exists) gives a solvable system, as a
check of the encoding.

For m = 4 Proposition 5 (the cup square) gives the same conclusion without neutrality; the computation
shows that the strata alone, with their restriction maps, already decide it.
Run: python3 strata_compatibility.py   (numpy and scipy; about half a minute)
"""
import itertools
import math
import random
from functools import reduce

import numpy as np
from scipy.optimize import Bounds, LinearConstraint, milp

import strata_obstructions as SO

def compose(p,q): return tuple(p[q[i]] for i in range(len(q)))
def closure(gens,n):
    e=tuple(range(n)); G={e}; frontier=[e]
    while frontier:
        new=[]
        for g in frontier:
            for s in gens:
                h=compose(s,g)
                if h not in G: G.add(h); new.append(h)
        frontier=new
    return frozenset(G)
def orbits(G,n):
    seen=set(); out=[]
    for i in range(n):
        if i in seen: continue
        o={g[i] for g in G}; seen|=o; out.append(sorted(o))
    return out
def cycles(p):
    seen=set(); out=[]
    for i in range(len(p)):
        if i in seen: continue
        c=[]; j=i
        while j not in seen: seen.add(j); c.append(j); j=p[j]
        out.append(tuple(c))
    return out
m=4
G4=SO.gamma_group(m,"N"); data=SO.element_data(G4,m)
def obstructed(P,n):
    """return (top, list of stratum obstructions) for K = P x S_4 (neutral)"""
    orb=orbits(P,n); g=reduce(math.gcd,[len(o) for o in orb])
    hits=[]
    for s in P:
        C=[r for r in P if compose(r,s)==compose(s,r)]
        cyc=cycles(s)
        for (gm,k,cr) in data:
            if k==m-1 and all(len(c)==1 for c in cyc): continue
            lengths={len(c) for c in cyc}
            dims={l:SO.dim_power(gm,l,m) for l in lengths}
            if k==0:
                if all(dims[l]>=1 for l in lengths): hits.append((s,'stage0'))
                continue
            short=[c for c in cyc if dims[len(c)]==k]
            # orbits of C on short cycles (as sets)
            sc=[frozenset(c) for c in short]; seen=set(); sizes=[]
            for c in sc:
                if c in seen: continue
                o={frozenset(r[x] for x in c) for r in C}; seen|=o; sizes.append(len(o))
            if k==1:
                if not short or (cr and all(z%2==0 for z in sizes)): hits.append((s,'stage1'))
                continue
            if not short: hits.append((s,'Z')); continue
            gh=reduce(math.gcd,sizes)
            if gh>1: hits.append((s,f'Z/{gh}'))
    return g, hits

def inv(p):
    q=[0]*len(p)
    for i,x in enumerate(p): q[x]=i
    return tuple(q)
def mul(a,b): return (compose(a[0],b[0]), a[1]^b[1])
def kclosure(gens,e):
    G={e}; fr=[e]
    while fr:
        nw=[]
        for g in fr:
            for s in gens:
                h=mul(s,g)
                if h not in G: G.add(h); nw.append(h)
        fr=nw
    return frozenset(G)
def circle_system(P,n):
    """Strata whose target is the circle fixed by one transposition tau (m >= 4): subgroups H of P x <tau>
    containing some element with renaming tau. Variables d[H,O] for short H-orbits O. Returns True if the
    compatible integer system is solvable (no obstruction found), else False."""
    e=(tuple(range(n)),0)
    PZ=[(s,z) for s in P for z in (0,1)]
    subs=set()
    for r in (1,2,3):
        for gens in itertools.combinations(PZ,r):
            H=kclosure(list(gens),e)
            if any(h[1] for h in H): subs.add(H)
    subs=list(subs)
    var={}; info={}
    for H in subs:
        seen=set(); orbs=[]
        for i in range(n):
            if i in seen: continue
            O=frozenset(h[0][i] for h in H); seen|=O
            short=any(h[1] for h in H if h[0][i]==i)
            orbs.append((O,short))
        info[H]=orbs
        for O,sh in orbs:
            if sh: var[(H,O)]=len(var)
    rows=[]; rhs=[]
    def eq(coefs,b): rows.append(coefs); rhs.append(b)
    for H in subs:
        sh=[O for O,s in info[H] if s]
        if not sh: return False
        eq({var[(H,O)]:1 for O in sh},1)
    # symmetry/conjugation by g in P x Z2 (renaming parts centralise tau; signs cancel)
    Hset=set(subs)
    for H in subs:
        for g in PZ:
            gi=(inv(g[0]),g[1])
            H2=frozenset(mul(mul(g,h),gi) for h in H)
            if H2 not in Hset: continue
            for O,s in info[H]:
                if s:
                    O2=frozenset(g[0][x] for x in O)
                    a,b=var[(H,O)],var[(H2,O2)]
                    if a!=b: eq({a:1,b:-1},0)
    # restriction: H subset H2 => X^{H2} in X^H; d[H2,O2] = sum of d[H,O] over short H-orbits O in O2
    for H in subs:
        for H2 in subs:
            if H2!=H and H<=H2:
                for O2,s2 in info[H2]:
                    if not s2: continue
                    c={var[(H2,O2)]:-1}
                    for O,s in info[H]:
                        if s and O<=O2: c[var[(H,O)]]=c.get(var[(H,O)],0)+1
                    eq(c,0)
    nv=len(var)
    A=np.zeros((len(rows),nv))
    for r,c in enumerate(rows):
        for k,v in c.items(): A[r,k]+=v
    res=milp(np.zeros(nv),constraints=LinearConstraint(A,np.array(rhs),np.array(rhs)),integrality=np.ones(nv),bounds=Bounds(-20,20))
    return res.status==0


def main():
    random.seed(0)
    for n in range(4, 8):
        perms = list(itertools.permutations(range(n)))
        seen, unob, fixedv = set(), [], []
        for _ in range(4000):
            gens = [random.choice(perms) for _ in range(random.choice([1, 2]))]
            P = closure(gens, n)
            if P in seen:
                continue
            seen.add(P)
            orb = orbits(P, n)
            if any(len(o) == 1 for o in orb):
                if len(P) <= 12:
                    fixedv.append(P)
                continue
            if reduce(math.gcd, [len(o) for o in orb]) != 1:
                continue
            if not obstructed(P, n)[1]:
                unob.append(P)
        res = [circle_system(P, n) for P in unob]
        san = [circle_system(P, n) for P in fixedv[:15]]
        print(f"n = {n}: {len(seen)} groups sampled; without fixed voter, gcd 1 and no single-stratum obstruction:"
              f" {len(unob)}, of which solvable when strata are compared: {sum(res)};"
              f" groups with a fixed voter tested: {len(san)}, all solvable: {all(san)}")
        for P in unob[:2]:
            print(f"     e.g. order {len(P)}, orbits {orbits(P, n)}")


if __name__ == "__main__":
    main()
