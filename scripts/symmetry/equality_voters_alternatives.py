"""Equality of voters and alternatives (EC-VA): the Equality Criterion with clones, ties as the exception.

Checks the examples and propositions of notes/equality-of-voters-and-alternatives.md:
  1. random ballot as tie-breaker fails the Equality Criterion (EC-V) at a profile of reversal pairs;
  2. the uniform lottery, the only neutral tie value EC-V allows there, fails independence of clones,
     while random ballot keeps the share of a cloned group;
  3. accumulation: adding reversal pairs leaves the maximal lottery fixed while the vote shares tend
     to the pair;
  4. three alternatives: the maximal lottery of a cycle is (m_bc, m_ca, m_ab)/sum, the axis of the
     rotation generated by the margin matrix; on a face of the cycle cone the set of maximal lotteries
     is the segment between the two one-sided limits;
  5. undecided profiles and Pfaffians: a 20-voter profile on four alternatives with no zero margin and
     a segment of maximal lotteries between two cycles; on random margin matrices the set of maximal
     lotteries has dimension nullity(G_E) - 1 (E the essential set), a unique lottery is carried by an
     odd number of candidates, and whenever the set is not a point some even subset of E has Pfaffian zero; with all margins odd it is a point; for four alternatives
     the Pfaffian is |p|^2 - |q|^2 for the left and right quaternion parts of the margin matrix;
  6. ties are within one vote: every single added ballot decides the undecided examples;
  7. tie-breakers under cloning: "a random voter chooses among all alternatives" gives a beaten
     candidate a chance when a clone of the winner ties with it; "a random voter chooses the maximal
     lottery that is best for their ballot" is independent of clones on random profiles with ties;
  8. a partial tie at which random ballot restricted to the tied candidates lies outside the set of
     maximal lotteries, while the voters' best maximal lotteries stay inside;
  9. Schulze and ranked pairs (margins) on small random profiles: ties within one vote, and the
     winning set under cloning.
Run: python3 equality_voters_alternatives.py   (needs numpy and scipy; one to two minutes)
"""
import itertools
from functools import lru_cache
import numpy as np
from scipy.optimize import linprog

rng = np.random.default_rng(3)


# ---------- profiles, margins, lotteries ----------

def margins(profile, m):
    G = np.zeros((m, m))
    for r in profile:
        for i, x in enumerate(r):
            for y in r[i + 1:]:
                G[x, y] += 1
                G[y, x] -= 1
    return G


def ml_point(G, c):
    """A maximal lottery of G minimising the objective c."""
    m = len(G)
    return linprog(c, A_ub=-G.T, b_ub=np.zeros(m), A_eq=np.ones((1, m)), b_eq=[1],
                   bounds=(0, 1), method="highs").x


def ml_range(G):
    """Smallest and largest probability of each candidate over the maximal lotteries of G."""
    m = len(G)
    out = np.zeros((m, 2))
    for i in range(m):
        e = np.zeros(m)
        e[i] = 1
        out[i] = ml_point(G, e)[i], ml_point(G, -e)[i]
    return out


def unique(G):
    c = rng.normal(size=len(G))
    return np.allclose(ml_point(G, c), ml_point(G, -c), atol=1e-7)


def ml_dimension(G, tries=14):
    pts = np.array([ml_point(G, rng.normal(size=len(G))) for _ in range(tries)])
    return np.linalg.matrix_rank(pts[1:] - pts[0], tol=1e-7)


def in_ml_set(G, p):
    return bool(np.all(p @ G >= -1e-7))


def best_for(G, ballot):
    """The maximal lottery that is lexicographically best for a ballot: the largest probability for
    its first candidate, then the largest for its second, and so on."""
    m = len(G)
    A_eq, b_eq = [np.ones(m)], [1.0]
    for x in ballot[:-1]:
        e = np.zeros(m)
        e[x] = 1
        res = linprog(-e, A_ub=-G.T, b_ub=np.zeros(m), A_eq=np.array(A_eq), b_eq=b_eq,
                      bounds=(0, 1), method="highs")
        A_eq.append(e)
        b_eq.append(res.x[x])
    return res.x


def voters_best(profile, m):
    """Maximal lotteries with ties broken by a random voter's best maximal lottery."""
    G = margins(profile, m)
    return sum(profile.count(r) / len(profile) * best_for(G, r) for r in set(profile))


def random_ballot(profile, m, among=None):
    among = range(m) if among is None else among
    out = np.zeros(m)
    for r in profile:
        out[next(x for x in r if x in among)] += 1 / len(profile)
    return out


def mcgarvey(G):
    """A profile with margin matrix G (all margins even): two ballots per margin of 2."""
    m = len(G)
    prof = []
    for x, y in itertools.permutations(range(m), 2):
        if G[x, y] > 0:
            rest = [z for z in range(m) if z not in (x, y)]
            for _ in range(int(G[x, y]) // 2):
                prof += [(x, y, *rest), (*reversed(rest), x, y)]
    return prof


def skew(m, upper):
    G = np.zeros((m, m))
    for (i, j), v in zip(itertools.combinations(range(m), 2), upper):
        G[i, j], G[j, i] = v, -v
    return G


def pfaffian(M):
    """Pfaffian of a skew-symmetric matrix given as nested lists of integers."""
    n = len(M)
    if n == 0:
        return 1
    if n % 2:
        return 0
    total = 0
    for j in range(1, n):
        if M[0][j]:
            rest = [k for k in range(1, n) if k != j]
            total += (-1) ** (j - 1) * M[0][j] * pfaffian([[M[r][c] for c in rest] for r in rest])
    return total


def pf_sub(G, S):
    return pfaffian([[int(G[i, j]) for j in S] for i in S])


a, b, c, d = range(4)

# ---------- 1. random ballot as tie-breaker at a profile of reversal pairs ----------
p = [(b, a, c), (c, a, b)]
q = p + [(a, b, c), (c, b, a)]
assert not margins(p, 3).any() and not margins(q, 3).any()
print("1. all margins zero in both profiles; random ballot:",
      random_ballot(p, 3).round(3), "->", random_ballot(q, 3).round(3))
assert not np.allclose(random_ballot(p, 3), random_ballot(q, 3))

# ---------- 2. clones at balanced profiles (the clone a' of a is the last index) ----------
for base, cloned, k in [([(a, b), (b, a)], [(a, 2, b), (b, 2, a)], 2),
                        ([(a, b, c), (c, b, a)], [(a, 3, b, c), (c, b, 3, a)], 3)]:
    rb_before, rb_after = random_ballot(base, k)[a], random_ballot(cloned, k + 1)
    print(f"2. {k} candidates: uniform gives a {1 / k:.3f}, the group a, a' {2 / (k + 1):.3f};"
          f" random ballot gives a {rb_before:.3f}, the group {rb_after[a] + rb_after[k]:.3f}")
    assert np.isclose(rb_before, rb_after[a] + rb_after[k])

# ---------- 3. accumulation ----------
base = [(a, b, c)] * 3 + [(b, c, a)] * 2 + [(c, a, b)] * 2
pair = [(a, c, b), (b, c, a)]
ml0 = ml_range(margins(base, 3))[:, 0]
for k in (0, 10, 1000):
    prof = base + pair * k
    ml = ml_range(margins(prof, 3))[:, 0]
    assert np.allclose(ml, ml0)
    print(f"3. k = {k:4d}: share of the pair {2 * k / len(prof):.4f}, maximal lottery {ml.round(3)}")

# ---------- 4. three alternatives ----------
def G3(x, y, z):                                          # x = m_ab, y = m_bc, z = m_ca
    return np.array([[0, x, -z], [-x, 0, y], [z, -y, 0]], dtype=float)

for _ in range(200):
    x, y, z = rng.uniform(0.1, 5, 3)
    axis = np.array([y, z, x])
    assert np.allclose(G3(x, y, z) @ axis, 0)             # the axis of the rotation
    for t in (1, 0.01):
        r = ml_range(G3(t * x, t * y, t * z))
        assert np.allclose(r[:, 0], axis / axis.sum(), atol=1e-7)
        assert np.allclose(r[:, 1], axis / axis.sum(), atol=1e-7)
print("4. cycle: maximal lottery = (m_bc, m_ca, m_ab)/sum = the kernel of the margin matrix (200 cases)")
for _ in range(200):                                      # face z = 0: a beats b, b beats c, a ties c
    x, y = rng.uniform(0.1, 5, 2)
    r = ml_range(G3(x, y, 0))
    cyc, cw = np.array([y, 0, x]) / (x + y), np.array([1, 0, 0])
    assert np.allclose(r[:, 1], np.maximum(cyc, cw), atol=1e-7)
    assert np.allclose(r[:, 0], np.minimum(cyc, cw), atol=1e-7)
print("   face of the cycle cone: the segment between the two one-sided limits (200 cases)")

# ---------- 5. undecided profiles and Pfaffians ----------
vals = [-4, -4, 2, -4, -2, -4]                            # m_ab, m_ac, m_ad, m_bc, m_bd, m_cd
G = skew(4, vals)
prof20 = mcgarvey(G)
assert np.array_equal(margins(prof20, 4), G) and pf_sub(G, range(4)) == 0
ends = [ml_point(G, np.array([0, 1.0, 0, 0])), ml_point(G, np.array([0, -1.0, 0, 0]))]
print(f"5. {len(prof20)} voters, margins {vals}, no zero margin, Pfaffian 0; maximal lotteries: the segment")
print(f"   from {ends[0].round(3)} (cycle a, c, d) to {ends[1].round(3)} (cycle a, b, d)")
for delta in (0.2, -0.2):
    w = list(vals)
    w[2] += delta
    Gp = skew(4, w)
    pf = w[0] * w[5] - w[1] * w[4] + w[2] * w[3]
    assert unique(Gp)
    lot = ml_point(Gp, np.zeros(4))
    print(f"   m_ad = {w[2]:.1f}: Pfaffian {pf:+.1f}, unique lottery {np.abs(lot).round(3)}")
    assert (lot[b] < 1e-9) == (pf < 0) and (lot[c] < 1e-9) == (pf > 0)

def check_structure(m, values, trials):
    undecided = beyond = 0
    for _ in range(trials):
        G = skew(m, rng.choice(values, size=m * (m - 1) // 2))
        if unique(G):
            E = np.flatnonzero(ml_point(G, np.zeros(m)) > 1e-9)
            assert len(E) % 2 == 1 and len(E) - np.linalg.matrix_rank(G[np.ix_(E, E)], tol=1e-9) == 1
            continue
        undecided += 1
        E = [i for i in range(m) if ml_range(G)[i, 1] > 1e-9]
        GE = G[np.ix_(E, E)]
        nullity = len(E) - np.linalg.matrix_rank(GE, tol=1e-9)
        assert ml_dimension(G) == nullity - 1
        zero_sets = [S for k in range(2, len(E) + 1, 2) for S in itertools.combinations(E, k)
                     if pf_sub(G, S) == 0]
        assert zero_sets
        beyond += all(len(S) > 2 for S in zero_sets)
    return undecided, beyond

for m, values, trials in [(4, [-3, -2, -1, 0, 1, 2, 3], 1200), (4, [-3, -2, -1, 1, 2, 3], 1200),
                          (5, [-3, -2, -1, 1, 2, 3], 800)]:
    u, bey = check_structure(m, values, trials)
    print(f"   m = {m}, margins from {values[0]}..{values[-1]}{'' if 0 in values else ' without 0'}:"
          f" {u} of {trials} undecided, {bey} with no pairwise tie among the essential candidates;"
          " dimension = nullity - 1 and a vanishing even Pfaffian in every case; unique lotteries on an odd set")
for m in (4, 5, 6):
    for _ in range(200):
        G = skew(m, rng.choice([-5, -3, -1, 1, 3, 5], size=m * (m - 1) // 2))
        assert unique(G)
        assert all(pf_sub(G, S) % 2 for k in range(2, m + 1, 2) for S in itertools.combinations(range(m), k))
print("   all margins odd: every even Pfaffian is odd and the maximal lottery is unique (200 cases each, m = 4, 5, 6)")

def left(p):
    p1, p2, p3 = p
    return np.array([[0, -p1, -p2, -p3], [p1, 0, -p3, p2], [p2, p3, 0, -p1], [p3, -p2, p1, 0]])

def right(q):
    q1, q2, q3 = q
    return np.array([[0, -q1, -q2, -q3], [q1, 0, q3, -q2], [q2, -q3, 0, q1], [q3, q2, -q1, 0]])

for _ in range(100):
    upper = rng.normal(size=6)
    M = skew(4, upper)
    mab, mac, mad, mbc, mbd, mcd = upper
    pq = -np.array([mab + mcd, mac - mbd, mad + mbc]) / 2, -np.array([mab - mcd, mac + mbd, mad - mbc]) / 2
    assert np.allclose(M, left(pq[0]) + right(pq[1]))     # x -> p x + x q on the quaternions
    assert np.isclose(mab * mcd - mac * mbd + mad * mbc, pq[0] @ pq[0] - pq[1] @ pq[1])
print("   four alternatives: margin matrix = left(p) + right(q), Pfaffian = |p|^2 - |q|^2 (100 cases)")

# ---------- 6. ties are within one vote ----------
examples = [(p, 3), (q, 3), (prof20, 4), (mcgarvey(G3(0, -4, -2)), 3), (mcgarvey(G3(2, 4, 0)), 3)]
for prof, m in examples:
    assert not unique(margins(prof, m))
    assert all(unique(margins(prof + [r], m)) for r in itertools.permutations(range(m)))
print(f"6. {len(examples)} undecided profiles: every single added ballot gives a unique maximal lottery")

# ---------- 7. tie-breakers under cloning ----------
before = [(a, b)] * 4 + [(b, a)] * 2                     # a wins, 4 to 2
after = [(a, 2, b)] * 2 + [(2, a, b)] * 2 + [(b, a, 2), (b, 2, a)]   # a' = 2 ties with a
r0, r1 = ml_range(margins(before, 2)), ml_range(margins(after, 3))
assert np.allclose(r0[:, 0], [1, 0]) and np.allclose(r0[:, 1], [1, 0])
assert np.allclose(r1[:, 0], [0, 0, 0]) and np.allclose(r1[:, 1], [1, 0, 1])
everyone, best = random_ballot(after, 3), voters_best(after, 3)
print(f"7. before cloning: a with certainty. After: a ties a', both beat b. A random voter choosing among")
print(f"   all alternatives gives (a, b, a') = {everyone.round(3)}; a random voter's best maximal lottery {best.round(3)}")
assert not in_ml_set(margins(after, 3), everyone) and np.allclose(best, [0.5, 0, 0.5])
for m, k, trials in [(3, 1, 300), (3, 2, 100), (4, 1, 100)]:
    ranks = list(itertools.permutations(range(m)))
    ties = 0
    for _ in range(trials):
        prof = [ranks[i] for i in rng.integers(len(ranks), size=int(rng.choice([2, 4, 6])))]
        x = int(rng.integers(m))
        cloned = []
        for r in prof:                                    # x becomes x and k clones, in random order
            i, group = r.index(x), [x] + list(range(m, m + k))
            rng.shuffle(group)
            cloned.append(r[:i] + tuple(group) + r[i + 1:])
        L, L2 = voters_best(prof, m), voters_best(cloned, m + k)
        merged = L2[:m].copy()
        merged[x] += L2[m:].sum()
        assert np.allclose(merged, L, atol=1e-7)
        assert in_ml_set(margins(prof, m), L) and in_ml_set(margins(cloned, m + k), L2)
        ties += not unique(margins(cloned, m + k))
    print(f"   voters' best maximal lottery, {m} candidates, one replaced by {k + 1} clones:"
          f" independent of clones in {trials} of {trials} cases ({ties} with a tie after cloning)")

# ---------- 8. a partial tie where restricted random ballot leaves the set ----------
G = G3(0, -4, -2)                                        # a ties b, a beats c by 2, c beats b by 4
prof = mcgarvey(G)
r = ml_range(G)
rrb = random_ballot(prof, 3, among=(a, b))
print(f"8. ranges a [{r[0, 0]:.3f}, {r[0, 1]:.3f}], b [{r[1, 0]:.3f}, {r[1, 1]:.3f}], c [{r[2, 0]:.3f},"
      f" {abs(r[2, 1]):.3f}]; random ballot among a, b: {rrb.round(3)}, inside: {in_ml_set(G, rrb)}")
assert not in_ml_set(G, rrb)
vb = voters_best(prof, 3)
print(f"   voters' best maximal lotteries: {np.abs(best_for(G, (a, b, c))).round(3)} for a first,"
      f" {np.abs(best_for(G, (b, a, c))).round(3)} for b first; the rule gives {vb.round(3)}, inside: {in_ml_set(G, vb)}")
assert in_ml_set(G, vb)

# ---------- 9. Schulze and ranked pairs, with margins as strengths ----------
def schulze(G):
    m = len(G)
    P = G.astype(float).copy()
    np.fill_diagonal(P, -np.inf)
    for k in range(m):
        for i in range(m):
            for j in range(m):
                if i != j:
                    P[i, j] = max(P[i, j], min(P[i, k], P[k, j]))
    return frozenset(x for x in range(m) if all(P[x, y] >= P[y, x] for y in range(m) if y != x))


def ranked_pairs(G):
    """Winners over all ways of ordering pairs of equal strength (Tideman 1987)."""
    m = len(G)
    strengths = sorted({G[x, y] for x in range(m) for y in range(m) if x != y and G[x, y] >= 0}, reverse=True)
    groups = [frozenset((x, y) for x in range(m) for y in range(m) if x != y and G[x, y] == s)
              for s in strengths]

    def reaches(locked, x, y):
        seen, todo = {x}, [x]
        while todo:
            u = todo.pop()
            for (s, t) in locked:
                if s == u and t not in seen:
                    seen.add(t)
                    todo.append(t)
        return y in seen

    @lru_cache(maxsize=None)
    def go(locked, gi, remaining):
        if not remaining:
            if gi + 1 == len(groups):
                return frozenset(x for x in range(m) if all(t != x for (_, t) in locked))
            return go(locked, gi + 1, groups[gi + 1])
        out = frozenset()
        for (x, y) in remaining:
            new = locked if reaches(locked, y, x) else locked | {(x, y)}
            out |= go(new, gi, remaining - {(x, y)})
        return out

    return go(frozenset(), 0, groups[0])


def clone_first(profile, new):
    out = []
    for r in profile:
        i = r.index(0)
        pair = (0, new) if rng.random() < 0.5 else (new, 0)
        out.append(r[:i] + pair + r[i + 1:])
    return out


for name, rule in [("Schulze", schulze), ("ranked pairs", ranked_pairs)]:
    ties = unresolved = 0
    for m, trials in [(3, 400), (4, 150)]:
        ranks = list(itertools.permutations(range(m)))
        for _ in range(trials):
            prof = [ranks[i] for i in rng.integers(len(ranks), size=int(rng.choice([2, 4, 6])))]
            if len(rule(margins(prof, m))) > 1:
                ties += 1
                unresolved += not any(len(rule(margins(prof + [r], m))) == 1 for r in ranks)
    clone_fail = clone_fail_decided = 0
    ranks = list(itertools.permutations(range(3)))
    for _ in range(600):
        prof = [ranks[i] for i in rng.integers(6, size=int(rng.choice([3, 4, 5, 6])))]
        W = rule(margins(prof, 3))
        W2 = rule(margins(clone_first(prof, 3), 4))
        if frozenset(0 if x == 3 else x for x in W2) != W:
            clone_fail += 1
            clone_fail_decided += len(W) == 1
    print(f"9. {name}: {ties} tied profiles, {unresolved} not decided by any single ballot;"
          f" cloning: winning set changed in {clone_fail} of 600 cases ({clone_fail_decided} with a single winner before)")

